#!/usr/bin/env node
// Serve the receiver from this directory, for working on it.
//
//   node bin/serve.js            http://localhost:6283
//   node bin/serve.js 8080

import { createServer } from 'node:http';
import { readFile, stat } from 'node:fs/promises';
import { extname, join, normalize, sep } from 'node:path';
import { ROOT } from './approval.js';

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json',
  '.md': 'text/markdown; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.woff2': 'font/woff2',
  '.txt': 'text/plain; charset=utf-8',
};

const port = Number(process.argv[2] || 6283);

createServer(async (req, res) => {
  try {
    let path = normalize(decodeURIComponent(new URL(req.url, 'http://x').pathname));
    if (path.includes('..')) throw new Error('no');
    let file = join(ROOT, path);
    if (!file.startsWith(ROOT + sep) && file !== ROOT) throw new Error('no');
    if ((await stat(file)).isDirectory()) file = join(file, 'index.html');
    const body = await readFile(file);
    res.writeHead(200, { 'content-type': TYPES[extname(file)] || 'application/octet-stream', 'cache-control': 'no-store' });
    res.end(body);
  } catch {
    res.writeHead(404, { 'content-type': 'text/plain' });
    res.end('Nothing on this frequency.\n');
  }
}).listen(port, '127.0.0.1', () => {
  process.stdout.write(`http://localhost:${port}\n`);
});
