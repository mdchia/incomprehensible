export const HEIGHT = 5;
export const ADVANCE = 4;

// How wide a line of text is, in cells.
export const measure = (text) => Math.max(0, text.length * ADVANCE - 1);

export const has = (ch) => ch in GLYPHS;

// Draw text onto anything with set(x, y, d). Returns the x after the last glyph.
export function write(target, text, x0, y0, d = 1) {
  let x = x0;
  for (const ch of String(text).toUpperCase()) {
    const rows = (GLYPHS[ch] || GLYPHS['?']).split(' ');
    for (let r = 0; r < 5; r++) {
      for (let c = 0; c < 3; c++) {
        if (rows[r][c] === '#') target.set(x + c, y0 + r, d);
      }
    }
    x += ADVANCE;
  }
  return x;
}
